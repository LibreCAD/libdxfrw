#!/usr/bin/env python3
"""Reproduce/check the fixed ISO8859-4 table from a pinned local Unicode file.

No downloads or file writes; ordinary builds/tests use the checked-in header.
"""
import argparse
import hashlib
from pathlib import Path
import sys

SOURCE_URL = "https://www.unicode.org/Public/MAPPINGS/ISO8859/8859-4.TXT"
SOURCE_SHA256 = "e717699903bef2144234279a598ce39b44502942c9cc23a2ce2069a65f46b00d"


def generate(path):
    with path.open("rb") as stream:
        raw = stream.read(65537)
    if len(raw) > 65536 or hashlib.sha256(raw).hexdigest() != SOURCE_SHA256:
        raise ValueError("mapping source differs from the pinned Unicode table")
    mapping = {}
    for line in raw.decode("utf8").splitlines():
        fields = line.split("#", 1)[0].split()
        if not fields:
            continue
        if len(fields) != 2:
            raise ValueError("unexpected mapping row")
        byte, scalar = (int(value, 16) for value in fields)
        if byte in mapping or not 0 <= scalar <= 0xFFFF or 0xD800 <= scalar <= 0xDFFF:
            raise ValueError("duplicate byte or invalid scalar")
        mapping[byte] = scalar
    if set(mapping) != set(range(256)) or len(set(mapping.values())) != 256:
        raise ValueError("mapping is not a complete bijection")
    if any(mapping[byte] != byte for byte in range(160)):
        raise ValueError("ASCII/C1 identity mapping differs")
    lines = [
        "// Generated by tools/generate_iso8859_4.py; do not edit by hand.",
        "// ISO/IEC 8859-4:1998, Unicode mapping table2.0 (1999-07-27).",
        "// Mapping data Copyright (c) 2015 Unicode, Inc.",
        "// Unicode License V3: see LICENSES/Unicode-3.0.txt.",
        "// Source: " + SOURCE_URL,
        "// SHA256: " + SOURCE_SHA256,
        "#ifndef DRW_CPTABLE_ISO8859_4_H",
        "#define DRW_CPTABLE_ISO8859_4_H",
        "",
        "// Byte80..FF; ASCII00..7F is handled by DRW_ConvTable.",
        "static constexpr int DRW_TableISO8859_4[128] = {",
    ]
    for first in range(128, 256, 8):
        values = ", ".join("0x%04X" % mapping[byte] for byte in range(first, first + 8))
        lines.append("    " + values + ", // %02X..%02X" % (first, first + 7))
    lines.extend(["};", "", "#endif", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("mapping", type=Path)
    parser.add_argument("--check", type=Path, help="compare an existing generated header")
    args = parser.parse_args()
    try:
        header = generate(args.mapping)
        if args.check is None:
            sys.stdout.write(header)
        elif args.check.read_text(encoding="utf8") != header:
            raise ValueError("generated header differs")
        else:
            print("ISO8859-4 generation: PASS (pinned source,256 unique rows,128 stored entries)")
    except (OSError, ValueError) as error:
        print("ISO8859-4 generation: " + str(error), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
