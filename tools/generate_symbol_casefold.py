#!/usr/bin/env python3
"""Generate/check locale-independent symbol ambiguity keys from pinned Unicode17.

No downloads or file writes. Ordinary builds use the generated header. The key
is the fixed-point closure of simple-uppercase then default full-case-folding;
it conservatively includes both relations, never rewrites exported spelling,
and does not claim a particular CAD consumer's locale/collation policy.
"""
import argparse
from functools import lru_cache
import hashlib
from pathlib import Path
import sys

FOLD_SHA = "ff8d8fefbf123574205085d6714c36149eb946d717a0c585c27f0f4ef58c4183"
DATA_SHA = "2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c"
BASE = "https://www.unicode.org/Public/17.0.0/ucd/"


def pinned(path, digest, limit):
    with path.open("rb") as stream:
        raw = stream.read(limit + 1)
    if len(raw) > limit or hashlib.sha256(raw).hexdigest() != digest:
        raise ValueError("Unicode source differs from pinned " + path.name)
    return raw.decode("utf8")


def generate(folding, data):
    folds, upper = {}, {}
    for line in pinned(folding, FOLD_SHA, 262144).splitlines():
        fields = [field.strip() for field in line.split("#", 1)[0].split(";")]
        if len(fields) >= 3 and fields[1] in {"C", "F"}:
            folds[int(fields[0], 16)] = tuple(int(cp, 16) for cp in fields[2].split())
    for line in pinned(data, DATA_SHA, 4194304).splitlines():
        fields = line.split(";")
        if fields[12]:
            upper[int(fields[0], 16)] = int(fields[12], 16)

    @lru_cache(maxsize=None)
    def key(cp):
        sequence = (cp,)
        for _ in range(16):
            mapped = tuple(value for item in sequence
                           for value in folds.get(upper.get(item, item), (upper.get(item, item),)))
            if len(mapped) > 32:
                raise ValueError("unbounded case closure")
            if mapped == sequence:
                return mapped
            sequence = mapped
        raise ValueError("case closure did not converge")

    for cp, mapping in folds.items():
        if key(cp) != tuple(value for item in mapping for value in key(item)):
            raise ValueError("full-fold relation escaped closure")
    for cp, mapping in upper.items():
        if key(cp) != key(mapping):
            raise ValueError("simple-uppercase relation escaped closure")
    values = []
    for cp in sorted(set(folds) | set(upper)):
        mapping = key(cp)
        if mapping == (cp,):
            continue
        if not 1 <= len(mapping) <= 3 or any(not 0 <= value <= 0x10FFFF
                or 0xD800 <= value <= 0xDFFF for value in mapping):
            raise ValueError("invalid/big mapped scalar sequence")
        if len("".join(chr(value) for value in mapping).encode("utf8")) > 3 * len(chr(cp).encode("utf8")):
            raise ValueError("UTF8 expansion exceeds the compiled3x bound")
        values.append((cp, mapping))
    lines = [
        "// Generated by tools/generate_symbol_casefold.py; do not edit by hand.",
        "// Mapping data Copyright (c) 2025 Unicode, Inc.",
        "// Unicode License V3: see LICENSES/Unicode-3.0.txt.",
        "// Unicode17 invariant simple-uppercase/default-full-fold closure.",
        "// Source: " + BASE + "CaseFolding.txt", "// SHA256: " + FOLD_SHA,
        "// Source: " + BASE + "UnicodeData.txt", "// SHA256: " + DATA_SHA,
        "#ifndef DRW_SYMBOL_CASEFOLD_DATA_H", "#define DRW_SYMBOL_CASEFOLD_DATA_H",
        "#include <cstdint>", "namespace drw_symbol_casefold_data {",
        "struct Mapping { std::uint32_t source, target[3]; unsigned count; };",
        "static constexpr Mapping mappings[] = {",
    ]
    for cp, mapping in values:
        padded = mapping + (0,) * (3 - len(mapping))
        lines.append("    {0x%Xu, {0x%Xu, 0x%Xu, 0x%Xu}, %du}," % ((cp,) + padded + (len(mapping),)))
    lines.extend(["};", "} // namespace drw_symbol_casefold_data", "#endif", ""])
    return "\n".join(lines), len(values), len(folds), len(upper)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("folding", type=Path)
    parser.add_argument("data", type=Path)
    parser.add_argument("--check", type=Path)
    args = parser.parse_args()
    try:
        header, rows, folds, upper = generate(args.folding, args.data)
        if args.check is None:
            sys.stdout.write(header)
        elif args.check.read_text(encoding="utf8") != header:
            raise ValueError("generated symbol-case data differs")
        else:
            print(f"Symbol case closure: PASS ({rows} rows; {folds} full-fold/{upper} uppercase relations; UTF8 expansion<=3x)")
    except (OSError, ValueError) as error:
        print(str(error), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
