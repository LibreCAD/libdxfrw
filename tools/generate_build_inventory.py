"""Keep canonical CMake, Automake and source-release inventories consistent.

Generation is a maintainer operation. Released configure/make builds need
neither Python nor Git; checks in an extracted source tree use the shipped list.
"""
from __future__ import annotations

import argparse
import hashlib
import io
from pathlib import Path, PurePosixPath
import re
import subprocess
import sys
import tarfile
import tempfile

ROOT = Path(__file__).resolve().parents[1]
MANAGED = {
    "tools/generate_build_inventory.py", "source-release-files.am",
    "source-release-files.txt", "src/source-files.am",
    "dwg2dxf/source-files.am", "dwg2dxf/source-files.cmake",
    "libdxfrw-autotools.pc.in", "docs/SOURCE_RELEASE.md",
}
RESEARCH_INPUTS = {
    "docs/research/visualstyle-slot-map-readiness-2026-10-15.json",
    "docs/research/visualstyle-slot-evidence-grades-2026-10-16.json",
}
GENERATED_RELEASE = {
    "Makefile.in", "src/Makefile.in", "dwg2dxf/Makefile.in", "configure",
    "aclocal.m4", "ar-lib", "compile", "config.guess", "config.sub",
    "depcomp", "install-sh", "ltmain.sh", "missing",
    "m4/libtool.m4", "m4/ltoptions.m4", "m4/ltsugar.m4",
    "m4/ltversion.m4", "m4/lt~obsolete.m4",
}


class InventoryError(ValueError):
    pass


def paths(items: list[str], generated_archive: bool = False) -> list[str]:
    seen = set()
    for name in items:
        path = PurePosixPath(name)
        grammar = r"[A-Za-z0-9_./+~-]+" if generated_archive else r"[A-Za-z0-9_./+-]+"
        if (not name or not re.fullmatch(grammar, name)
                or path.is_absolute() or ".." in path.parts or path.as_posix() != name
                or name == "." or name in seen):
            raise InventoryError("unsafe or duplicate inventory path: " + repr(name))
        seen.add(name)
    return items


def cmake_list(text: str, key: str, prefix: str = "${CMAKE_CURRENT_LIST_DIR}/") -> list[str]:
    matches = re.findall(r"set\(" + re.escape(key) + r"\s+([^)]*)\)", text, re.S)
    if len(matches) != 1:
        raise InventoryError("expected one literal CMake list: " + key)
    items = []
    for token in matches[0].split():
        token = token.removeprefix('"').removesuffix('"')
        if prefix and not token.startswith(prefix):
            raise InventoryError("nonliteral CMake item: " + token)
        items.append(token[len(prefix):])
    return paths(items)


def in_release(name: str) -> bool:
    # Keep append-only execution evidence out of its own archive/hash cycle.
    # The two historical reports below are actual CMake test inputs.
    return (name != "DWG_DXF_OPEN_SOURCE_PARITY_PLAN.md"
            and (not name.startswith("docs/research/") or name in RESEARCH_INPUTS))


def tracked(root: Path) -> list[str] | None:
    try:
        top = subprocess.check_output(["git", "-C", str(root), "rev-parse", "--show-toplevel"], stderr=subprocess.DEVNULL)
        if Path(top.decode().strip()).resolve() != root.resolve():
            return None  # A source archive inside another checkout is not that checkout.
        return paths(subprocess.check_output(["git", "-C", str(root), "ls-files", "-z"]).decode().split("\0")[:-1])
    except (OSError, subprocess.CalledProcessError):
        return None


def assignment(key: str, values: list[str]) -> str:
    return key + " =" + (" \\\n" + " \\\n".join("    " + item for item in values) if values else "") + "\n"


def generated(root: Path, listed: list[str]) -> dict[str, str]:
    core = (root / "libdxfrw_sources.cmake").read_text()
    cli = (root / "dwg2dxf/source-files.cmake").read_text()
    sources = cmake_list(core, "LIBDXFRW_SOURCES")
    public = cmake_list(core, "LIBDXFRW_PUBLIC_HEADERS")
    private = cmake_list(core, "LIBDXFRW_PRIVATE_HEADERS")
    paths(sources + public + private)
    cli_sources = cmake_list(cli, "LIBDXFRW_CLI_SOURCES")
    cli_headers = cmake_list(cli, "LIBDXFRW_CLI_HEADERS")
    paths(cli_sources + cli_headers)
    actual_sources = {p for p in listed if p.startswith("src/") and p.endswith(".cpp")}
    actual_headers = {p for p in listed if p.startswith("src/") and p.endswith(".h")}
    actual_cli = {p[8:] for p in listed if p.startswith("dwg2dxf/") and p.endswith((".cpp", ".h"))}
    if set(sources) != actual_sources or set(public + private) != actual_headers:
        raise InventoryError("core CMake inventory differs from tracked sources/headers")
    if set(cli_sources + cli_headers) != actual_cli:
        raise InventoryError("CLI CMake inventory differs from tracked sources/headers")
    closure = cmake_list((root / "CMakeLists.txt").read_text(), "libdxfrw_transitive_hdrs", "")
    if not set(closure) <= set(private):
        raise InventoryError("installed transitive headers must be classified private headers")
    header = "# Generated by tools/generate_build_inventory.py; do not edit.\n"
    strip = lambda items: [p.removeprefix("src/") for p in items]
    selected = paths(sorted(set(p for p in listed if in_release(p)) | MANAGED))
    return {
        "src/source-files.am": header + assignment("libdxfrw_la_SOURCES", strip([p for p in sources if p != "src/drw_entities.cpp"]))
            + assignment("libdxfrw_entities_la_SOURCES", ["drw_entities.cpp"])
            + assignment("library_include_HEADERS", strip(public))
            + assignment("nobase_library_include_HEADERS", strip(closure))
            + assignment("dist_noinst_HEADERS", strip([p for p in private if p not in closure])),
        "dwg2dxf/source-files.am": header + assignment("dwg2dxf_SOURCES", cli_sources)
            + assignment("dist_noinst_HEADERS", cli_headers),
        "source-release-files.am": header + assignment("EXTRA_DIST", selected),
        "source-release-files.txt": "\n".join(selected) + "\n",
    }


def check_archive(root: Path, archive_path: Path, listed: list[str]) -> None:
    expected = set(listed)
    # A streaming pass avoids repeatedly decompressing a large gzip/bzip2
    # archive when the manifest and physical archive have different orders.
    with tarfile.open(archive_path, mode="r|*") as archive:
        members = set()
        prefixes = set()
        for item in archive:
            paths([item.name.rstrip("/")], generated_archive=True)
            prefixes.add(item.name.split("/", 1)[0])
            if Path(item.name).name.startswith("._") or not (item.isfile() or item.isdir()):
                raise InventoryError("unexpected archive member: " + item.name)
            if item.isfile():
                _, separator, name = item.name.partition("/")
                if not separator or name in members:
                    raise InventoryError("duplicate or unrooted archive file: " + item.name)
                members.add(name)
                if name not in expected and name not in GENERATED_RELEASE:
                    raise InventoryError("unlisted archive file: " + name)
                if name in expected:
                    content = archive.extractfile(item)
                    if content is None or hashlib.sha256(content.read()).digest() != hashlib.sha256((root / name).read_bytes()).digest():
                        raise InventoryError("archive bytes differ: " + name)
        if len(prefixes) != 1:
            raise InventoryError("archive must have one source root")
        if expected - members:
            raise InventoryError("archive omits " + sorted(expected - members)[0])
    print("Archive inventory: PASS (%d exact source files)" % len(listed))


def self_test() -> None:
    controls = 0
    for bad in ["../secret", "/tmp/file", "src//one.h", "src/a b.h", "src/$(id).h", "src/a\nb.h", "src/a~.h", "C:/file", ".", ""]:
        try:
            paths([bad])
        except InventoryError:
            controls += 1
        else:
            raise AssertionError(bad)
    for items in [["a", "a"], ["src/a.h", "src/a.h"]]:
        try:
            paths(items)
        except InventoryError:
            controls += 1
        else:
            raise AssertionError(items)
    valid = 'set(FILES "${CMAKE_CURRENT_LIST_DIR}/src/a.cpp"\n "${CMAKE_CURRENT_LIST_DIR}/src/b.h")'
    assert cmake_list(valid, "FILES") == ["src/a.cpp", "src/b.h"]
    for bad in [valid + "\n" + valid, 'set(FILES ${OTHER})', 'set(FILES "${CMAKE_CURRENT_LIST_DIR}/../secret")']:
        try:
            cmake_list(bad, "FILES")
        except InventoryError:
            controls += 1
        else:
            raise AssertionError(bad)
    assert not in_release("docs/research/new-receipt.json")
    assert not in_release("DWG_DXF_OPEN_SOURCE_PARITY_PLAN.md")
    assert all(in_release(p) for p in RESEARCH_INPUTS)
    assert paths(["package/m4/lt~obsolete.m4"], generated_archive=True)
    with tempfile.TemporaryDirectory() as directory:
        root = Path(directory)
        assert tracked(root) is None
        (root / "src").mkdir()
        (root / "src/a.cpp").write_bytes(b"// authored source\n")
        cases = [("good", "package/src/a.cpp", b"// authored source\n"),
                 ("bytes", "package/src/a.cpp", b"// changed source\n"),
                 ("path", "package/../secret", b"private"),
                 ("extra", "package/untracked.dxf", b"unlisted")]
        for kind, name, data in cases:
            path = root / (kind + ".tar.gz")
            with tarfile.open(path, "w:gz") as archive:
                item = tarfile.TarInfo(name); item.size = len(data)
                archive.addfile(item, io.BytesIO(data))
            try:
                check_archive(root, path, ["src/a.cpp"])
            except InventoryError:
                if kind == "good":
                    raise
                controls += 1
            else:
                assert kind == "good", kind
    print("Build inventory self-test: PASS (%d refusal controls; archive bytes/policy and no-Git lookup)" % controls)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT)
    action = parser.add_mutually_exclusive_group(required=True)
    action.add_argument("--write", action="store_true")
    action.add_argument("--check", action="store_true")
    action.add_argument("--self-test", action="store_true")
    parser.add_argument("--archive", type=Path)
    args = parser.parse_args()
    if args.self_test:
        self_test()
        return 0
    root = args.root.resolve()
    listed = tracked(root)
    if listed is None:
        if args.write:
            raise InventoryError("regeneration requires the actual Git checkout")
        listed = paths((root / "source-release-files.txt").read_text().splitlines())
    outputs = generated(root, listed)
    if args.write:
        for name, content in outputs.items():
            (root / name).write_text(content)
    else:
        for name, content in outputs.items():
            if (root / name).read_text() != content:
                raise InventoryError("stale " + name + "; run --write")
    released = paths(outputs["source-release-files.txt"].splitlines())
    for name in released:
        path = root / name
        if path.is_symlink() or not path.is_file():
            raise InventoryError("missing or nonregular release input: " + name)
    print("Build inventory: PASS (%d released files; complete core/CLI sources and headers)" % len(released))
    if args.archive:
        check_archive(root, args.archive, released)
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (InventoryError, OSError, UnicodeError, tarfile.TarError) as exc:
        print("Build inventory: FAIL: " + str(exc), file=sys.stderr)
        raise SystemExit(1)
